// Instant outcome statuses.
const (
	InstantExisting       = "existing"        // published lecture returned, no generation
	InstantStarted        = "started"         // new generation job (stage events on StreamURL)
	InstantAttached       = "attached"        // joined a running job for the same target
	InstantNeedsSelection = "needs_selection" // free query resolved; client picks a concept
	InstantAlreadyLearned = "already_learned" // every objective at that depth is done
)

// InstantRequest is POST /v1/lectures/instant.
type InstantRequest struct {
	ConceptID string `json:"conceptId"`
	Query     string `json:"query"`
	Depth     int    `json:"depth"`
	// AutoStart: for a free query, immediately generate for the starting point.
	AutoStart bool `json:"autoStart"`
	// ParentLectureID / ParentAnchor: set when opened via "이 개념 더 깊게" from
	// a lecture; the resulting lecture is linked under it (lecture_links).
	ParentLectureID string `json:"parentLectureId"`
	ParentAnchor    string `json:"parentAnchor"`
	// StudyRequestID: set when started from a study request; a knowledge_gap
	// context fills the lecture's KnowledgeGaps (KNOWLEDGE-DESIGN §4.7).
	StudyRequestID string `json:"studyRequestId"`
}

// InstantResponse describes what happened.
type InstantResponse struct {
	Status     string      `json:"status"`
	ConceptID  string      `json:"conceptId,omitempty"`
	LectureID  string      `json:"lectureId,omitempty"`
	JobID      string      `json:"jobId,omitempty"`
	StreamURL  string      `json:"streamUrl,omitempty"`
	Resolution *Resolution `json:"resolution,omitempty"`
	// InquiryID: set with status "inquiry" — a deep lecture asked from a reading
	// thread whose concept is the lecture being read became a question explanation.
	InquiryID string `json:"inquiryId,omitempty"`
}

// ErrTargetBusy: a library job is generating the same target right now.
var ErrTargetBusy = errors.New("this lecture is being generated by another job")

// StartInstant returns an existing published lecture or starts a reviewed
// generation (stage events on the stream URL). Free queries are resolved to a
// concept first. A failed generation publishes nothing, so calling this again
// ('다시 만들기') starts a new job.
func (s *Service) StartInstant(ctx context.Context, userID string, req InstantRequest) (InstantResponse, error) {
	var resolution *Resolution
	conceptID := strings.TrimSpace(req.ConceptID)
	if conceptID == "" {
		res, err := s.Resolve(ctx, userID, req.Query, func() (string, error) { return s.Keys.RequestKey(ctx, userID) })
		if err != nil {
			return InstantResponse{}, err
		}
		resolution = &res
		if len(res.ConceptIDs) == 0 || !req.AutoStart {
			return InstantResponse{Status: InstantNeedsSelection, Resolution: resolution}, nil
		}
		conceptID = res.StartingConceptID
		if conceptID == "" {
			return InstantResponse{Status: InstantAlreadyLearned, ConceptID: res.ConceptIDs[0], Resolution: resolution}, nil
		}
	}

	t, err := s.instantTarget(ctx, userID, conceptID, req.Depth, req.Query)
	if errors.Is(err, learning.ErrNothingToLearn) {
		return InstantResponse{Status: InstantAlreadyLearned, ConceptID: conceptID, Resolution: resolution}, nil
	}
	if err != nil {
		return InstantResponse{}, err
	}
	t.personal.gaps = s.studyRequestGaps(ctx, userID, strings.TrimSpace(req.StudyRequestID))
	resp := InstantResponse{ConceptID: conceptID, Resolution: resolution}

	// A lecture asked for the learner's gaps is written for them: an existing
	// lecture of the same objectives never saw those gaps, so it is not reused.
	if len(t.personal.gaps) == 0 {
		existing, err := s.Store.PublishedLectureCovering(ctx, userID, conceptID, t.Plan.Depth, t.Plan.ObjectiveIDs, t.Plan.Language, t.Plan.ReaderLevel, store.LangExact)
		if err == nil {
			resp.Status, resp.LectureID = InstantExisting, existing.ID
			s.linkDeeper(ctx, userID, req, resp)
			return resp, nil
		}
		if !errors.Is(err, store.ErrNotFound) {
			return InstantResponse{}, err
		}
	}

	target := learning.TargetKey(t.Plan)
	if jobID, ok := s.Hub.ActiveJob(target); ok {
		resp.Status, resp.JobID, resp.StreamURL = InstantAttached, jobID, streamURL(jobID)
		s.linkDeeper(ctx, userID, req, resp)
		return resp, nil
	}
	if err := s.CheckBudget(ctx, userID, true); err != nil {
		return InstantResponse{}, err
	}
	apiKey, err := s.Keys.RequestKey(ctx, userID)
	if err != nil {
		return InstantResponse{}, err
	}
	job, _, err := s.Store.CreateJob(ctx, store.NewJob{
		IdempotencyKey: fmt.Sprintf("%s:%s:%s", learning.JobInstant, target, store.RandomToken()),
		Kind:           learning.JobInstant, UserID: userID, ConceptID: conceptID,
		ObjectiveKey: t.Plan.ObjectiveKey, Depth: t.Plan.Depth, Reason: "instant", Language: t.Plan.Language, ReaderLevel: t.Plan.ReaderLevel,
	})
	if errors.Is(err, store.ErrJobActive) {
		if jobID, ok := s.Hub.ActiveJob(target); ok {
			resp.Status, resp.JobID, resp.StreamURL = InstantAttached, jobID, streamURL(jobID)
			s.linkDeeper(ctx, userID, req, resp)
			return resp, nil
		}
		return InstantResponse{}, ErrTargetBusy
	}
	if err != nil {
		return InstantResponse{}, err
	}

	jobID, started := s.Hub.Start(job.ID, target, func(emit func(Event)) {
		s.runInstant(apiKey, userID, job.ID, t, emit)
	})
	resp.JobID, resp.StreamURL = jobID, streamURL(jobID)
	resp.Status = InstantStarted
	if !started {
		resp.Status = InstantAttached
		if ferr := s.Store.FinishJob(ctx, job.ID, store.JobOutcome{Status: "skipped", Reason: "attached to " + jobID}); ferr != nil {
			logf("skip duplicate job %s: %v", job.ID, ferr)
		}
	}
	s.linkDeeper(ctx, userID, req, resp)
	return resp, nil
}

// linkDeeper records the "더 깊게" link for a successful instant response.
// A failed link must not block learning, so it is logged, not returned.
func (s *Service) linkDeeper(ctx context.Context, userID string, req InstantRequest, resp InstantResponse) {
	if req.ParentLectureID == "" || (resp.LectureID == "" && resp.JobID == "") {
		return
	}
	err := s.Store.LinkDeeper(ctx, store.DeeperLink{
		UserID: userID, ParentLecture: req.ParentLectureID, ChildLectureID: resp.LectureID,
		ChildJobID: resp.JobID, ChildConceptID: resp.ConceptID, Anchor: req.ParentAnchor,
	})
	if err != nil {
		logf("link deeper %s -> %s%s: %v", req.ParentLectureID, resp.LectureID, resp.JobID, err)
	}
}

func streamURL(jobID string) string { return "/v1/lectures/instant/" + jobID + "/stream" }
