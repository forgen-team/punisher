const instantTimeout = 8 * time.Minute

// Instant outcome statuses.
const (
	InstantExisting       = "existing"        // published lecture returned, no generation
	InstantStarted        = "started"         // new streaming job
	InstantAttached       = "attached"        // joined a running job for the same target
	InstantNeedsSelection = "needs_selection" // free query resolved; client picks a concept
	InstantAlreadyLearned = "already_learned" // every objective at that depth is done
)

// InstantRequest is POST /v1/lectures/instant.
type InstantRequest struct {
	ConceptID string `json:"conceptId"`
	Query     string `json:"query"`
	Depth     int    `json:"depth"`
	// AutoStart: for a free query, immediately generate for the starting point.
	AutoStart bool `json:"autoStart"`
	// ParentLectureID / ParentAnchor: set when opened via "이 개념 더 깊게" from
	// a lecture; the resulting lecture is linked under it (lecture_links).
	ParentLectureID string `json:"parentLectureId"`
	ParentAnchor    string `json:"parentAnchor"`
}

// InstantResponse describes what happened.
type InstantResponse struct {
	Status     string      `json:"status"`
	ConceptID  string      `json:"conceptId,omitempty"`
	LectureID  string      `json:"lectureId,omitempty"`
	JobID      string      `json:"jobId,omitempty"`
	StreamURL  string      `json:"streamUrl,omitempty"`
	Resolution *Resolution `json:"resolution,omitempty"`
}

// ErrTargetBusy: a library job is generating the same target right now.
var ErrTargetBusy = errors.New("this lecture is being generated by another job")

// StartInstant returns an existing published lecture or starts a streaming
// generation. Free queries are resolved to a concept first.
func (s *Service) StartInstant(ctx context.Context, userID string, req InstantRequest) (InstantResponse, error) {
	var resolution *Resolution
	conceptID := strings.TrimSpace(req.ConceptID)
	if conceptID == "" {
		res, err := s.Resolve(ctx, userID, req.Query, func() (string, error) { return s.Keys.RequestKey(ctx, userID) })
		if err != nil {
			return InstantResponse{}, err
		}
		resolution = &res
		if len(res.ConceptIDs) == 0 || !req.AutoStart {
			return InstantResponse{Status: InstantNeedsSelection, Resolution: resolution}, nil
		}
		conceptID = res.StartingConceptID
		if conceptID == "" {
			return InstantResponse{Status: InstantAlreadyLearned, ConceptID: res.ConceptIDs[0], Resolution: resolution}, nil
		}
	}

	t, err := s.instantTarget(ctx, userID, conceptID, req.Depth, req.Query)
	if errors.Is(err, learning.ErrNothingToLearn) {
		return InstantResponse{Status: InstantAlreadyLearned, ConceptID: conceptID, Resolution: resolution}, nil
	}
	if err != nil {
		return InstantResponse{}, err
	}
	resp := InstantResponse{ConceptID: conceptID, Resolution: resolution}

	existing, err := s.Store.PublishedLectureCovering(ctx, userID, conceptID, t.Plan.Depth, t.Plan.ObjectiveIDs)
	if err == nil {
		resp.Status, resp.LectureID = InstantExisting, existing.ID
		s.linkDeeper(ctx, userID, req, resp)
		return resp, nil
	}
	if !errors.Is(err, store.ErrNotFound) {
		return InstantResponse{}, err
	}

	target := learning.TargetKey(t.Plan)
	if jobID, ok := s.Hub.ActiveJob(target); ok {
		resp.Status, resp.JobID, resp.StreamURL = InstantAttached, jobID, streamURL(jobID)
		s.linkDeeper(ctx, userID, req, resp)
		return resp, nil
	}
	if err := s.CheckBudget(ctx, userID, true); err != nil {
		return InstantResponse{}, err
	}
	apiKey, err := s.Keys.RequestKey(ctx, userID)
	if err != nil {
		return InstantResponse{}, err
	}
	job, _, err := s.Store.CreateJob(ctx, store.NewJob{
		IdempotencyKey: fmt.Sprintf("%s:%s:%s", learning.JobInstant, target, store.RandomToken()),
		Kind:           learning.JobInstant, UserID: userID, ConceptID: conceptID,
		ObjectiveKey: t.Plan.ObjectiveKey, Depth: t.Plan.Depth, Reason: "instant",
	})
	if errors.Is(err, store.ErrJobActive) {
		if jobID, ok := s.Hub.ActiveJob(target); ok {
			resp.Status, resp.JobID, resp.StreamURL = InstantAttached, jobID, streamURL(jobID)
			s.linkDeeper(ctx, userID, req, resp)
			return resp, nil
		}
		return InstantResponse{}, ErrTargetBusy
	}
	if err != nil {
		return InstantResponse{}, err
	}

	jobID, started := s.Hub.Start(job.ID, target, func(emit func(Event)) {
		s.runInstant(apiKey, userID, job.ID, t, emit)
	})
	resp.JobID, resp.StreamURL = jobID, streamURL(jobID)
	resp.Status = InstantStarted
	if !started {
		resp.Status = InstantAttached
		if ferr := s.Store.FinishJob(ctx, job.ID, store.JobOutcome{Status: "skipped", Reason: "attached to " + jobID}); ferr != nil {
			logf("skip duplicate job %s: %v", job.ID, ferr)
		}
	}
	s.linkDeeper(ctx, userID, req, resp)
	return resp, nil
}

// linkDeeper records the "더 깊게" link for a successful instant response.
// A failed link must not block learning, so it is logged, not returned.
func (s *Service) linkDeeper(ctx context.Context, userID string, req InstantRequest, resp InstantResponse) {
	if req.ParentLectureID == "" || (resp.LectureID == "" && resp.JobID == "") {
		return
	}
	err := s.Store.LinkDeeper(ctx, store.DeeperLink{
		UserID: userID, ParentLecture: req.ParentLectureID, ChildLectureID: resp.LectureID,
		ChildJobID: resp.JobID, ChildConceptID: resp.ConceptID, Anchor: req.ParentAnchor,
	})
	if err != nil {
		logf("link deeper %s -> %s%s: %v", req.ParentLectureID, resp.LectureID, resp.JobID, err)
	}
}

func streamURL(jobID string) string { return "/v1/lectures/instant/" + jobID + "/stream" }

// instantAttempts: one automatic rewrite when the first output does not parse
// or fails structural validation (the reason is fed back to the model).
const instantAttempts = 2

// StageRewriting is the status stage emitted before the automatic rewrite;
// clients drop the streamed text and show "형식 문제로 다시 쓰는 중".
const StageRewriting = "rewriting"

// runInstant streams one lecture. It runs detached from the HTTP request.
// If the output cannot be parsed or fails validation, it is rewritten once
// with the problems as revision notes; every attempt is kept in the job's
// attempt_log. A second failure to parse fails the job (never saved).
func (s *Service) runInstant(apiKey, userID, jobID string, t Target, emit func(Event)) {
	ctx, cancel := context.WithTimeout(context.Background(), instantTimeout)
	defer cancel()
	var u usage
	var tries []store.AttemptRecord
	fail := func(code string, err error) {
		logf("instant job %s failed: %v", jobID, err)
		o := u.outcome("failed", code, err, "")
		if len(tries) > 0 {
			o.Attempts = tries
		}
		if ferr := s.Store.FinishJob(ctx, jobID, o); ferr != nil {
			logf("finish job %s: %v", jobID, ferr)
		}
		msg := DescribeLLMError(err)
		if msg == "" {
			msg = "강의 생성에 실패했습니다: " + err.Error()
		}
		emit(Event{Type: EventError, Data: map[string]string{"code": code, "message": msg}})
	}
	if err := s.Store.StartJob(ctx, jobID); err != nil {
		fail("store_error", err)
		return
	}

	maxTokens := s.Cfg.LectureMaxTokens
	if maxTokens <= 0 {
		maxTokens = defaultMaxTokens
	}
	notes := ""
	var a Attempt
	for n := 1; n <= instantAttempts; n++ {
		if n == 1 {
			emit(Event{Type: EventStatus, Data: map[string]string{"stage": "generating"}})
		} else {
			emit(Event{Type: EventStatus, Data: map[string]string{"stage": StageRewriting, "reason": tries[len(tries)-1].Message}})
		}
		res, err := s.LLM.Stream(ctx, apiKey, llm.MessagesRequest{
			Model: s.Cfg.LectureModel, System: t.Prompts.Text(prompts.BlockTeacherSystem, prompts.LectureVars(t.Prompt)),
			User:      prompts.Lecture(t.LectureContext(), "", notes, t.Prompts),
			MaxTokens: maxTokens, Timeout: instantTimeout,
		}, func(delta string) error {
			emit(Event{Type: EventDelta, Data: map[string]string{"text": delta}})
			return nil
		})
		u.add(res)
		if err != nil {
			fail("llm_error", err)
			return
		}
		if res.Truncated() {
			fail("truncated", fmt.Errorf("model output truncated at max_tokens (%d)", maxTokens))
			return
		}
		emit(Event{Type: EventStatus, Data: map[string]string{"stage": "validating"}})
		a = Attempt{Number: n, Markup: res.Text}
		a.Content, a.Issues, a.ParseErr = t.parseAndValidate(res.Text)
		tries = append(tries, a.Record())
		if a.ParseErr == nil && len(a.Issues) == 0 {
			break
		}
		notes = RevisionNotes(a)
	}
	if a.ParseErr != nil {
		fail("unusable_output", fmt.Errorf("%w: %v", ErrUnusableOutput, a.ParseErr))
		return
	}
	status, flagged, reason := "published", false, ""
	if len(a.Issues) > 0 {
		status, flagged = "needs_revision", true
		parts := make([]string, 0, len(a.Issues))
		for _, i := range a.Issues {
			parts = append(parts, i.String())
		}
		reason = strings.Join(parts, "; ")
	}
	saved, err := s.saveLecture(ctx, t, a.Content, learning.JobInstant, status, userID, jobID, u.model, flagged, reason)
	if err != nil {
		fail("store_error", err)
		return
	}
	done := u.outcome("succeeded", status, nil, saved.ID)
	done.Attempts = tries
	if err := s.Store.FinishJob(ctx, jobID, done); err != nil {
		logf("finish job %s: %v", jobID, err)
	}
	if err := s.Store.ResolveLinkJob(ctx, jobID, saved.ID); err != nil {
		logf("resolve links of job %s: %v", jobID, err)
	}
	emit(Event{Type: EventDone, Data: map[string]any{
		"lectureId": saved.ID, "status": status, "flagged": flagged, "issues": issuesOrEmpty(a.Issues),
		"attempts": len(tries),
	}})
}

func issuesOrEmpty(issues []lecture.Issue) []lecture.Issue {
	if issues == nil {
		return []lecture.Issue{}
	}
	return issues
}
